declare(strict_types=1);

namespace Go\Yii3\GoAopBridge\Tests\App\Service;

/**
 * Shared service recording what the aspects observed, injected into them by the Yii container
 */
final class Journal
{
    /** @var list<string> */
    public array $entries = [];

    public function record(string $entry): void
    {
        $this->entries[] = $entry;
    }
}
